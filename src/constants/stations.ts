// 検索・フィルタリング用のヘルパー
export const getStationsByLine = (lineId: string): Station[] => {
  return stations.filter(station =>
    station.lines.some(line => line.id === lineId)
  );
};

export const searchStations = (query: string): Station[] => {
  const normalizedQuery = query.toLowerCase();
  return stations.filter(station =>
    station.name.toLowerCase().includes(normalizedQuery) ||
    station.nameKana.includes(normalizedQuery)
  );
};

export const getLineById = (lineId: string): Line | undefined => {
  return lines.find(line => line.id === lineId);
};

export const getStationById = (stationId: string): Station | undefined => {
  return stations.find(station => station.id === stationId);
};

// 駅をIDで検索するためのマップ（後方互換性のため）
export const stationMap = new Map<string, Station>(
  stations.map(station => [station.id, station])
);

// 路線をIDで検索するためのマップ（後方互換性のため）
export const lineMap = new Map<string, Line>(
  lines.map(line => [line.id, line])
);
